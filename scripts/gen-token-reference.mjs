#!/usr/bin/env node
/**
 * Write the design-token table into docs/design-system.md (#1269).
 *
 *   node scripts/gen-token-reference.mjs           # rewrite the block
 *   node scripts/gen-token-reference.mjs --check   # exit 1 if it would change
 *
 * Reads the same `src/_data/designTokens.js` module the site builds from, so
 * the documented table and the rendered style guide can never disagree: both
 * come from `site.css`'s own `:root`.
 *
 * Only the block between the TOKENS markers is machine-managed. The prose
 * around it stays maintainer-written, the same split the roadmap autostamp in
 * docs/roadmap-2026.md already uses.
 *
 * --check makes this safe to wire into CI later without doing so now: nothing
 * calls it yet, and a docs table that lags a token by a day harms nobody.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const designTokens = require("../src/_data/designTokens.js");

const DOC = "docs/design-system.md";
const BEGIN = "<!-- TOKENS:BEGIN -->";
const END = "<!-- TOKENS:END -->";

const check = process.argv.includes("--check");
const data = designTokens();

const escape = (s) => String(s).replace(/\|/g, "\\|");

const lines = [
  BEGIN,
  `<!-- Generated by scripts/gen-token-reference.mjs from ${data.source}. Do not edit by hand. -->`,
  "",
  `**${data.count} tokens** across ${data.familyCount} families, in the order they appear in the stylesheet.`,
  "",
];

for (const group of data.groups) {
  lines.push(`#### ${group.label} (\`--${group.family}-*\`)`, "");
  lines.push("| Token | Value | Notes |", "|---|---|---|");
  for (const t of group.tokens) {
    lines.push(`| \`${t.name}\` | \`${escape(t.value)}\` | ${t.note ? escape(t.note) : ""} |`);
  }
  lines.push("");
}

lines.push(END);
const block = lines.join("\n");

const doc = readFileSync(DOC, "utf8");
const from = doc.indexOf(BEGIN);
const to = doc.indexOf(END);

if (from === -1 || to === -1) {
  console.error(`error: ${DOC} has no ${BEGIN} / ${END} markers. Add them where the table belongs.`);
  process.exit(1);
}

const next = doc.slice(0, from) + block + doc.slice(to + END.length);

if (next === doc) {
  console.log(`${DOC} is already current (${data.count} tokens, ${data.familyCount} families)`);
  process.exit(0);
}

if (check) {
  console.error(`error: ${DOC} is stale. Run: node scripts/gen-token-reference.mjs`);
  process.exit(1);
}

writeFileSync(DOC, next);
console.log(`updated ${DOC}: ${data.count} tokens, ${data.familyCount} families`);
